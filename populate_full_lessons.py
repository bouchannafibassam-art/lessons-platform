def main():
    db = sqlite3.connect(DB_PATH)
    db.row_factory = sqlite3.Row

    levels = db.execute("SELECT * FROM levels ORDER BY order_num").fetchall()
    updated = 0
    missing = []

    for lvl in levels:
        order_num = lvl["order_num"]
        level_id = lvl["id"]
        subject_content = CONTENT.get(order_num, {})

        subjects = db.execute("SELECT * FROM subjects WHERE level_id=?", (level_id,)).fetchall()
        for subj in subjects:
            pair = subject_content.get(subj["name"])
            if not pair:
                missing.append((lvl["name"], subj["name"]))
                continue
            title, content = pair
            first_lesson = db.execute(
                "SELECT id FROM lessons WHERE subject_id=? ORDER BY id LIMIT 1", (subj["id"],)
            ).fetchone()
            if first_lesson:
                video_query = f"{lvl['name']} {subj['name']} {title} شرح درس"
                video_url = "https://www.youtube.com/results?search_query=" + quote_plus(video_query)
                db.execute(
                    "UPDATE lessons SET title=?, content=?, video_url=?, video_file=NULL WHERE id=?",
                    (title, content, video_url, first_lesson["id"]),
                )
                updated += 1

    db.commit()
    db.close()
    print(f"تم تحديث {updated} درس بمحتوى كامل (شرح + مثال + تمرين).")
    if missing:
        print("ماكاينش محتوى معد لـ:", missing)


if __name__ == "__main__":
    main()
